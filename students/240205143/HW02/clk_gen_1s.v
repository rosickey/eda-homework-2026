`timescale 1s/1ms
//==============================================================================
// 文件名 : clk_gen_1s.v
// 功能   : 1 秒周期时钟发生器（在 clk_gen.v 基础上修改）
// 端口   : 与原 clk_gen 模块完全一致，只有 clk 一个输出端口
// 说明   : 通过修改 timescale 把时间单位变为 1 s，#0.5 即 0.5 s，
//          每 0.5 s 翻转一次，因此时钟周期为 1 s。
//==============================================================================
module clk_gen_1s(clk);
    output reg clk;

    initial begin
        clk = 1'b1;              // 从高电平开始，t = 1 s 时出现第一个上升沿
        forever #0.5 clk = ~clk; // 0.5 s 翻转一次，周期 1 s
    end
endmodule
