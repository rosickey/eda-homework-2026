`timescale 1ns/1ns

//============================================================
// 模块名称：led
// 功能描述：LED显示模块
//           将控制信号连接到LED输出
//           高电平点亮LED，低电平熄灭
//
// 端口说明：
//   ctrl     - 控制信号输入（来自cd4017的某一位输出）
//   led_out  - LED输出，高电平亮
//============================================================
module led(ctrl, led_out);
    input ctrl;        // 控制信号输入
    output led_out;    // LED输出，高电平点亮

    // 直接连线：控制信号直接输出到LED
    assign led_out = ctrl;

endmodule
