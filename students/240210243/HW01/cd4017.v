`timescale 1ns/1ns

//============================================================
// 模块名称：cd4017
// 功能描述：十进制计数器/脉冲分配器（约翰逊计数器结构）
//           输出为独热码(one-hot)，每次只有一位为高电平
//           在时钟上升沿，高电平依次从q[0]移到q[9]，然后循环
//
// 端口说明：
//   clk  - 时钟输入，上升沿触发
//   en   - 计数使能，高电平有效（en=1时计数，en=0时保持）
//   clr  - 异步清零，高电平有效（clr=1时，q[0]=1，其余为0）
//   q    - 10位独热码输出，q[0]~q[9]依次输出高电平
//============================================================
module cd4017(clk, en, clr, q);
    input clk;          // 时钟输入
    input en;           // 使能端，高电平有效
    input clr;          // 清零端，高电平有效，异步清零
    output reg [9:0] q; // 10位独热码输出

    // 时序逻辑：异步清零，同步计数
    always @(posedge clk or posedge clr) begin
        if (clr) begin
            // 清零：q[0]=1，其余为0
            q <= 10'b0000000001;
        end else if (en) begin
            // 使能有效时，在时钟上升沿移位
            if (q[9] == 1'b1) begin
                // 如果当前是q[9]为高，下一个周期回到q[0]
                q <= 10'b0000000001;
            end else begin
                // 否则左移一位，高电平向右移动
                q <= q << 1;
            end
        end
        // en=0时，q保持不变（不需要写，reg默认保持）
    end

endmodule
